export interface CloudWord { text: string; count: number }

/** Устойчивые выражения проверяются первыми, чтобы не распадаться на отдельные слова. */
const PHRASES: [string, string][] = [
  ['критическ\\p{L}* мышлен', 'Критическое мышление'], ['обратн\\p{L}* связ', 'Обратная связь'],
  ['читательск\\p{L}* грамотност', 'Читательская грамотность'], ['функциональн\\p{L}* грамотност', 'Функциональная грамотность'],
  ['искусственн\\p{L}* интеллект', 'ИИ'], ['русск\\p{L}* язык', 'Русский язык'], ['экономи\\p{L}* времени', 'Экономия времени'],
  ['индивидуальн\\p{L}* подход', 'Индивидуальный подход'], ['литературн\\p{L}* геро', 'Литературный герой'], ['работ\\p{L}* в группах', 'Работа в группах'],
];
const TERMS: [string, string][] = [
  ['ии(?!\\p{L})|ai(?!\\p{L})|жи(?!\\p{L})', 'ИИ'], ['нейросет|chatgpt|чатгпт|gpt', 'Нейросеть'], ['текст', 'Текст'], ['анализ', 'Анализ'],
  ['задани', 'Задания'], ['ученик|школьник', 'Ученики'], ['учител|педагог', 'Учитель'], ['факт(?!ор)', 'Факты'], ['провер', 'Проверка'],
  ['сочинен', 'Сочинение'], ['эссе', 'Эссе'], ['литератур', 'Литература'], ['произведен', 'Произведения'], ['геро[йяюео]', 'Литературный герой'],
  ['диалог', 'Диалог'], ['вопрос', 'Вопросы'], ['запрос|промпт', 'Запросы'], ['словар', 'Словарь'], ['лексик', 'Лексика'], ['грамматик', 'Грамматика'],
  ['орфограф|пунктуац|грамотност', 'Грамотность'], ['реч(?:ь|и|ев|ью)', 'Речь'], ['чтени|читат', 'Чтение'], ['творч', 'Творчество'], ['мотивац', 'Мотивация'],
  ['интерес', 'Интерес'], ['вовлеч', 'Вовлечённость'], ['редактир', 'Редактирование'], ['обучени', 'Обучение'], ['развити|развива', 'Развитие'],
  ['подготов', 'Подготовка'], ['инструмент', 'Инструменты'], ['технолог', 'Технологии'], ['презентац', 'Презентации'], ['тест(?!\\p{L}*ир)', 'Тесты'],
  ['визуал|иллюстрац|картинк', 'Визуализация'], ['игр(?:а|ы|у|е|ов)', 'Игра'], ['проект', 'Проекты'], ['сотруднич', 'Сотрудничество'], ['оценива', 'Оценивание'],
  ['рефлекс', 'Рефлексия'], ['помощник', 'Помощник'], ['этик|этичн', 'Этика'], ['ответственн', 'Ответственность'], ['самостоят', 'Самостоятельность'],
  ['дифференц|разноуровнев|индивидуальн', 'Индивидуальный подход'], ['смысл', 'Смысл'], ['понимани', 'Понимание'], ['мышлен', 'Мышление'],
];
const compile = (l: [string, string][]) => l.map(([p, label]) => [new RegExp(`(?<!\\p{L})(?:${p})\\p{L}*`, 'gu'), label] as const);
const PHRASE_RE = compile(PHRASES); const TERM_RE = compile(TERMS);

/** Главные темы из ответов. Каждая тема считается один раз на ответ. */
export function buildCloud(ideas: string[], limit = 14): CloudWord[] {
  const counts = new Map<string, number>();
  ideas.forEach((idea) => {
    let text = idea.toLowerCase().replace(/ё/g, 'е'); const found = new Set<string>();
    PHRASE_RE.forEach(([re, label]) => { if (text.search(re) >= 0) { found.add(label); text = text.replace(re, ' '); } });
    TERM_RE.forEach(([re, label]) => { if (text.search(re) >= 0) found.add(label); });
    found.forEach((l) => counts.set(l, (counts.get(l) ?? 0) + 1));
  });
  return [...counts].map(([text, count]) => ({ text, count })).sort((a, b) => b.count - a.count || a.text.localeCompare(b.text, 'ru')).slice(0, limit);
}

/** Положение слова: две колонки по сторонам дерева, в процентах от экрана. */
export function cloudSlot(i: number) {
  const row = Math.floor(i / 2); const left = i % 2 === 0;
  return { side: left ? 'left' : 'right', edge: 2.5 + ((row * 37) % 3) * 1.6, top: 7 + row * 8.6 } as const;
}
export function cloudSize(count: number, max: number, length: number) {
  const size = max <= 1 ? 1.75 : 1.45 + 1.75 * ((count - 1) / (max - 1));
  return Math.min(size, 24 / (length * 0.56));
}
